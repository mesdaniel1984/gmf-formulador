'use strict';
const assert=require('node:assert/strict');
const {day,period,model}=require('../painel-admin.js');
assert.equal(day('31/02/2026'),null);
assert.equal(day('29/02/2024'),'2024-02-29');
assert.equal(day('2026-09-23T12:00:00Z'),'2026-09-23');
assert.equal(day(''),null);
assert.equal(period(null,'',''),null);
assert.deepEqual(period([{data:null},{data:'23/09/2026'},{data:'2026-09-24'}],'2026-09-23','2026-09-23'),[{data:'23/09/2026'}]);
const state={fontes:{ncs:{registros:[{id:'a',status:'Aberta',data:'2026-09-23',prazo:'2026-09-22'},{id:'b',status:'Fechada',data:'2026-09-23',prazo:'2026-09-20'}]},sac:{registros:[]},licencas:{registros:[{titulo:'Alvará',prazo:'2026-09-21'},{titulo:'Sem data',prazo:''}]},docs:{registros:[{status:'Obsoleto',prazo:'2020-01-01'}]}},laudos:[{status:'Emitido',data:'23/09/2026'},{status:'Rascunho',data:'2026-09-23'}],entrada_sac:null,atendimento_humano:[]};
const m=model(state,'2026-09-23','2026-09-23','2026-09-23');
assert.equal(m.groups.find(g=>g.key==='laudos').count,1);
assert.equal(m.groups.find(g=>g.key==='ncs').count,1);
assert.equal(m.groups.find(g=>g.key==='sac').count,0);
assert.equal(m.groups.find(g=>g.key==='entrada_sac').count,null);
assert.equal(m.groups.find(g=>g.key==='atendimento_humano').count,0);
assert.equal(m.groups.find(g=>g.key==='licencas').count,2);
assert.deepEqual(m.alerts.map(a=>a.due),['2026-09-21','2026-09-22']);
const after=model(state,'2026-09-24','','2026-09-23');
assert.equal(after.groups[0].count,0);
assert.equal(after.alerts.length,2,'current overdue obligations are independent of event period');
console.log('Painel Admin: datas, fontes ausentes, período, contagens e atrasos passaram.');
